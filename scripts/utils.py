def найти_файлы_тикеров(тикеры=None, сектор=None):
    """Находит файлы отчётов по заданным тикерам или сектору.
    Возвращает словарь: {тикер: путь_к_файлу}
    """
    результат = {}
    for путь_к_файлу in glob.glob(os.path.join(ДИРЕКТОРИЯ_ОТЧЁТОВ, "**", "*.md"), recursive=True):
        имя_файла = os.path.basename(путь_к_файлу)
        совпадение = re.match(rf"^({ШАБЛОН_ТИКЕРА})_", имя_файла, re.IGNORECASE)
        if not совпадение:
            continue
        тикер_из_имени = совпадение.group(1)

        if сектор:
            папка = os.path.basename(os.path.dirname(путь_к_файлу))
            if папка.lower() != сектор.lower():
                continue

        if тикеры is None or тикер_из_имени in тикеры:
            результат[тикер_из_имени] = путь_к_файлу

    return результат


def получить_тикер_из_имени_файла(путь):
    """Извлекает тикер и название компании из имени файла отчёта."""
    имя_файла = os.path.basename(путь)
    совпадение = re.match(rf"^({ШАБЛОН_ТИКЕРА})_(.+)\.md$", имя_файла, re.IGNORECASE)
    if совпадение:
        return совпадение.group(1), совпадение.group(2)
    return None, None


# =============================================================================
# Разбор области действия
# =============================================================================

def разобрать_аргументы_области(аргументы):
    """Разбирает аргументы командной строки в область действия: список тикеров, сектор или None (все).
    Возвращает (список_тикеров_или_None, сектор_или_None, строка_описания)
    """
    if not аргументы:
        return None, None, "все тикеры"
    elif аргументы[0] == "--сектор":
        if len(аргументы) < 2:
            print("Параметр --сектор требует название сектора")
            sys.exit(1)
        сектор = " ".join(аргументы[1:])
        return None, сектор, f"все тикеры из сектора: {сектор}"
    else:
        тикеры = [
            т.strip() for т in аргументы if re.match(rf"^{ШАБЛОН_ТИКЕРА}$", т.strip(), re.IGNORECASE)
        ]
        return тикеры, None, f"{len(тикеры)} тикеров: {', '.join(тикеры)}"


