def заменить_секцию(содержимое, заголовок_секции, новое_содержимое, следующий_заголовок=None):
    """Заменяет содержимое между заголовок_секции и следующий_заголовок.
    Если следующий_заголовок равен None, заменяет до конца файла.
    """
    if следующий_заголовок:
        шаблон = rf"({re.escape(заголовок_секции)}\n)(.*?)(?=\n{re.escape(следующий_заголовок)})"
        return re.sub(шаблон, rf"\g<1>{новое_содержимое}\n", содержимое, flags=re.DOTALL)
    else:
        шаблон = rf"{re.escape(заголовок_секции)}.*"
        return re.sub(шаблон, f"{заголовок_секции}\n{новое_содержимое}\n", содержимое, flags=re.DOTALL)


def создать_русский_парсер(**kwargs):
    """Создаёт ArgumentParser с русскоязычными заголовками секций помощи."""
    парсер = argparse.ArgumentParser(**kwargs)
    for г in парсер._action_groups:
        if г.title == "positional arguments":
            г.title = "Позиционные аргументы"
        elif г.title in ("optional arguments", "options"):
            г.title = "Параметры"
    return парсер
