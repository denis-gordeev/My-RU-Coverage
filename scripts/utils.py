def is_cyrillic_name(s):
    """Проверяет, записана ли строка преимущественно на кириллице."""
    if not s:
        return False

    cyrillic = sum(1 for c in s if "\u0400" <= c <= "\u04FF")
    return cyrillic > len(s) * 0.3


