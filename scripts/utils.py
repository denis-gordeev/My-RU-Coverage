def является_кириллическим_именем(строка):
    """Проверяет, записана ли строка преимущественно на кириллице."""
    if not строка:
        return False

    cyrillic = sum(1 for c in строка if "\u0400" <= c <= "\u04FF")
    return cyrillic > len(строка) * 0.3


