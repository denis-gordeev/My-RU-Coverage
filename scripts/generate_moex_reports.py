СУФФИКСЫ_КОРОТКОГО_ИМЕНИ = (" ао", " ап", "-ао", "-ап")


def нормализовать_название_компании(тикер, короткое_имя):
    переопределение = ПЕРЕОПРЕДЕЛЕНИЯ_ОТЧЁТОВ.get(тикер, {})
    if переопределение.get("название"):
        return переопределение["название"]

    очищенное = (короткое_имя or тикер).strip()
    if очищенное[:1].lower() == "i" and len(очищенное) > 1 and очищенное[1].isalpha():
        очищенное = очищенное[1:]
    нижний = очищенное.lower()
    for суффикс in СУФФИКСЫ_КОРОТКОГО_ИМЕНИ:
        if нижний.endswith(суффикс):
            очищенное = очищенное[: -len(суффикс)]
            break
    return очищенное.strip(" .") or тикер


def отобрать_элементы_очереди(отчёт, запрошенные_тикеры=None):
    очередь = отчёт["следующая_очередь"]
    if not запрошенные_тикеры:
        return очередь

    соответствие = {элемент["тикер"]: элемент for элемент in очередь}
    элементы = []
    for тикер in запрошенные_тикеры:
        элемент = соответствие.get(тикер)
        if элемент is None:
            элементы.append(
                {
                    "тикер": тикер,
                    "название": ПЕРЕОПРЕДЕЛЕНИЯ_ОТЧЁТОВ.get(тикер, {}).get("название", тикер),
                }
            )
        else:
            элементы.append(элемент)
    return элементы


def построить_путь_вывода(тикер, название_компании, название_сектора):
    безопасный_сектор = очистить_имя_папки(название_сектора)
    имя_файла = f"{тикер}_{название_компании}.md"
    return os.path.join(ДИРЕКТОРИЯ_ОТЧЁТОВ, безопасный_сектор, имя_файла)


def создать_отчёты(элементы, лимит=None, пробный_запуск=False):
    существующие = найти_файлы_тикеров()
    создано = 0
    пропущено = 0

    for элемент in элементы:
        if лимит is not None and создано >= лимит:
            break

        тикер = элемент["тикер"]
        if тикер in существующие:
            print(f"  {тикер}: пропуск (карточка уже существует)")
            пропущено += 1
            continue

        переопределение = ПЕРЕОПРЕДЕЛЕНИЯ_ОТЧЁТОВ.get(тикер, {})
        название_компании = нормализовать_название_компании(тикер, элемент.get("название", тикер))
        сектор = переопределение.get("сектор")
        отрасль = переопределение.get("отрасль")
        содержимое, определённый_сектор = сгенерировать_отчёт(тикер, название_компании, сектор, отрасль)
        целевой_сектор = сектор or определённый_сектор or "Не определено"
        путь_вывода = построить_путь_вывода(тикер, название_компании, целевой_сектор)

        if пробный_запуск:
            print(f"  {тикер}: черновик -> {путь_вывода}")
            создано += 1
            continue

        os.makedirs(os.path.dirname(путь_вывода), exist_ok=True)
        with open(путь_вывода, "w", encoding="utf-8") as файл:
            файл.write(содержимое)
        print(f"  {тикер}: создано -> {путь_вывода}")
        создано += 1

    return создано, пропущено


def main():
    настроить_вывод()
    парсер = создать_русский_парсер(
        description=(
            "Создать базовые MOEX-карточки по живой очереди из MOEX ISS без "
            "опоры на устаревший Excel."
        )
    )
    парсер.add_argument(
        "тикеры",
        nargs="*",
        help="Явно указанные тикеры. Если не заданы, используется очередь непокрытых тикеров из MOEX ISS.",
    )
    парсер.add_argument("--дата", help="Дата состава индекса в формате YYYY-MM-DD")
    парсер.add_argument(
        "--индекс",
        dest="индексы",
        action="append",
        help=(
            "Код индекса MOEX ISS. Можно повторять несколько раз; по умолчанию "
            "используются MOEXBC и MOEXBMI."
        ),
    )
    парсер.add_argument(
        "--лимит",
        type=int,
        default=5,
        help="Сколько новых карточек создать из начала очереди. По умолчанию 5.",
    )
    парсер.add_argument(
        "--все-непокрытые",
        action="store_true",
        help="Игнорировать лимит --лимит и обработать всю очередь непокрытых тикеров.",
    )
    парсер.add_argument(
        "--пробный-запуск",
        action="store_true",
        help="Показать, какие карточки будут созданы, без записи файлов.",
    )
    аргументы = парсер.parse_args()

    коды_индексов = аргументы.индексы or КОДЫ_ИНДЕКСОВ_ПО_УМОЛЧАНИЮ
    try:
        отчёт = построить_отчёт(коды_индексов, аргументы.дата)
    except HTTPError as ошибка:
        print(f"Ошибка HTTP при запросе MOEX ISS: {ошибка}", file=sys.stderr)
        sys.exit(1)
    except URLError as ошибка:
        print(f"Сетевой сбой при запросе MOEX ISS: {ошибка}", file=sys.stderr)
        sys.exit(1)

    элементы = отобрать_элементы_очереди(отчёт, [тикер.upper() for тикер in аргументы.тикеры])
    if not элементы:
        print("Очередь уже покрыта: новых карточек для создания нет.")
        return

    лимит = None if аргументы.все_непокрытые or аргументы.тикеры else max(аргументы.лимит, 0)
    print(
        f"Генерирую базовые MOEX-карточки из очереди {', '.join(коды_индексов)} "
        f"на дату {отчёт['дата_торгов']}..."
    )
    создано, пропущено = создать_отчёты(элементы, лимит=лимит, пробный_запуск=аргументы.пробный_запуск)
    print(f"\nГотово. Создано: {создано} | Пропущено: {пропущено}")


if __name__ == "__main__":
    main()
