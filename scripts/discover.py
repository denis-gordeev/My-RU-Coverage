def определить_профиль(ключевое_слово):
    """Автоопределение профиля секторов по содержанию запроса."""
    for слово in КЛЮЧЕВЫЕ_СЛОВА_ТЕХ:
        if слово in ключевое_слово:
            return "технологический"
    for слово in КЛЮЧЕВЫЕ_СЛОВА_ЭНЕРГЕТИКИ:
        if слово in ключевое_слово:
            return "энергетический"
    return "все"


def искать_в_отчётах(ключевое_слово, фильтр_секторов=None):
    """Ищет упоминания темы по карточкам эмитентов."""
    результаты = []

    for папка_сектора in sorted(os.listdir(ДИРЕКТОРИЯ_ОТЧЁТОВ)):
        путь_сектора = os.path.join(ДИРЕКТОРИЯ_ОТЧЁТОВ, папка_сектора)
        if not os.path.isdir(путь_сектора):
            continue

        if фильтр_секторов and папка_сектора not in фильтр_секторов:
            continue

        for файл in sorted(os.listdir(путь_сектора)):
            if not файл.endswith(".md"):
                continue
            совпадение = re.match(rf"^({ШАБЛОН_ТИКЕРА})_(.+)\.md$", файл, re.IGNORECASE)
            if not совпадение:
                continue

            тикер, компания = совпадение.group(1), совпадение.group(2)
            путь_к_файлу = os.path.join(путь_сектора, файл)

            with open(путь_к_файлу, "r", encoding="utf-8") as дескриптор:
                содержимое = дескриптор.read()

            разделение_финансов = re.split(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["финансовый_обзор"], содержимое, maxsplit=1)
            текст = разделение_финансов[0]

            число_со_ссылкой = len(re.findall(r"\[\[" + re.escape(ключевое_слово) + r"\]\]", текст))

            шаблон_голых = r"(?<!\[\[)" + re.escape(ключевое_слово) + r"(?!\]\])"
            голые_совпадения = list(re.finditer(шаблон_голых, текст))
            количество_голых = len(голые_совпадения)

            if число_со_ссылкой > 0 or количество_голых > 0:
                контексты = []
                for совпадение in голые_совпадения[:3]:
                    начало = max(0, совпадение.start() - 30)
                    конец = min(len(текст), совпадение.end() + 30)
                    фрагмент = текст[начало:конец].replace("\n", " ").strip()
                    контексты.append(f"...{фрагмент}...")

                роль = "упоминание"
                for имя_секции, имя_роли in [
                    (РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["описание_деятельности"], "основное_направление"),
                    (РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["цепочка_поставок"], "цепочка_поставок"),
                    (РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["клиенты_и_поставщики"], "клиент_поставщик"),
                ]:
                    совпадение_секции = re.search(
                        rf"{имя_секции}\n(.*?)(?=\n## |\Z)", текст, re.DOTALL
                    )
                    if совпадение_секции and ключевое_слово in совпадение_секции.group(1):
                        роль = имя_роли
                        break

                результаты.append({
                    "тикер": тикер,
                    "компания": компания,
                    "сектор": папка_сектора,
                    "путь": путь_к_файлу,
                    "с_викилинком": число_со_ссылкой,
                    "без_викилинка": количество_голых,
                    "роль": роль,
                    "контексты": контексты,
                })

    return результаты


def применить_викилинки(результаты, ключевое_слово):
    """Добавляет [[викилинки]] там, где термин найден без разметки."""
    применено = 0
    for р in результаты:
        if р["без_викилинка"] == 0:
            continue

        with open(р["путь"], "r", encoding="utf-8") as ф:
            содержимое = ф.read()

        совпадение_финансов = re.search(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["финансовый_обзор"], содержимое)
        if not совпадение_финансов:
            continue

        текст = содержимое[: совпадение_финансов.start()]
        финансовая_часть = содержимое[совпадение_финансов.start() :]
        шаблон = (
            r"(?<!\[\[)"
            + re.escape(ключевое_слово)
            + r"(?!\]\])(?![A-Za-z\u0400-\u04FF])"
        )
        новый_текст, количество = re.subn(шаблон, f"[[{ключевое_слово}]]", текст)

        if количество > 0:
            содержимое = новый_текст + финансовая_часть
            with open(р["путь"], "w", encoding="utf-8") as ф:
                ф.write(содержимое)
            применено += количество

    return применено


def вывести_отчёт(результаты, ключевое_слово):
    """Печатает сводку по найденным совпадениям."""
    if not результаты:
        print(f"\nНе найдено компаний, где упоминается «{ключевое_слово}».")
        return

    по_роли = defaultdict(list)
    for результат in результаты:
        по_роли[результат["роль"]].append(результат)

    print(f"\n{'=' * 60}")
    print(f"Компании, связанные с темой «{ключевое_слово}»: {len(результаты)}")
    print(f"{'=' * 60}")

    метки_ролей = {
        "основное_направление": "Связь через основное направление",
        "цепочка_поставок": "Связь через цепочку поставок",
        "клиент_поставщик": "Связь через клиентов/поставщиков",
        "упоминание": "Прочие упоминания",
    }

    for роль, метка in метки_ролей.items():
        записи = по_роли.get(роль, [])
        if not записи:
            continue
        print(f"\n### {метка} ({len(записи)})")
        for р in sorted(записи, key=lambda x: x["тикер"]):
            статус_ссылки = "✓" if р["с_викилинком"] > 0 else "○"
            пометка_о_голых = f" (+{р['без_викилинка']} без [[викилинк]])" if р["без_викилинка"] > 0 else ""
            print(f"  {статус_ссылки} {р['тикер']} {р['компания']} ({р['сектор']}){пометка_о_голых}")
            for контекст in р["контексты"][:1]:
                print(f"    -> {контекст}")


def главный():
    настроить_вывод()

    if len(sys.argv) < 2:
        print("Использование:")
        print('  python scripts/discover.py "импортозамещение"        # искать по всем секторам')
        print('  python scripts/discover.py "СПГ" --умный              # автофильтр секторов')
        print('  python scripts/discover.py "нефтегаз" --сектор Энергетика')
        print('  python scripts/discover.py "редкоземы" --применить     # проставить [[викилинки]]')
        print('  python scripts/discover.py "СПГ" --применить --пересобрать  # + пересобрать темы/граф')
        sys.exit(1)

    ключевое_слово = sys.argv[1]
    аргументы = sys.argv[2:]

    применять = "--применить" in аргументы
    пересобирать = "--пересобрать" in аргументы
    умный = "--умный" in аргументы

    фильтр_секторов = None
    if "--сектор" in аргументы:
        индекс = аргументы.index("--сектор")
        if индекс + 1 < len(аргументы):
            фильтр_секторов = {аргументы[индекс + 1]}
    elif "--секторы" in аргументы:
        индекс = аргументы.index("--секторы")
        if индекс + 1 < len(аргументы):
            фильтр_секторов = set(строка.strip() for строка in аргументы[индекс + 1].split(","))
    elif умный:
        профиль = определить_профиль(ключевое_слово)
        фильтр_секторов = УМНЫЕ_ПРОФИЛИ[профиль]
        if фильтр_секторов:
            print(
                f"Умный режим: профиль '{МЕТКИ_ПРОФИЛЕЙ.get(профиль, профиль)}', поиск по {len(фильтр_секторов)} секторам"
            )
            print("  Внимание: возможны пропуски межсекторальных совпадений. Для полного охвата запускайте без --умный.")

    print(f"Ищу «{ключевое_слово}»...")
    результаты = искать_в_отчётах(ключевое_слово, фильтр_секторов)

    вывести_отчёт(результаты, ключевое_слово)

    if применять and результаты:
        количество_голых = sum(р["без_викилинка"] for р in результаты)
        if количество_голых > 0:
            применено = применить_викилинки(результаты, ключевое_слово)
            print(f"\nДобавлено {применено} вхождений [[{ключевое_слово}]].")
        else:
            print(f"\nВсе упоминания уже размечены как [[{ключевое_слово}]].")

    if пересобирать:
        print("\nПересобираю тематические страницы...")
        subprocess.run(
            [sys.executable, os.path.join(КОРЕНЬ_ПРОЕКТА, "scripts", "build_themes.py")],
            cwd=КОРЕНЬ_ПРОЕКТА,
        )
        print("Пересобираю сетевой граф...")
        subprocess.run(
            [sys.executable, os.path.join(КОРЕНЬ_ПРОЕКТА, "scripts", "build_network.py")],
            cwd=КОРЕНЬ_ПРОЕКТА,
        )
        print("Пересобираю индекс викилинков...")
        subprocess.run(
            [sys.executable, os.path.join(КОРЕНЬ_ПРОЕКТА, "scripts", "build_wikilink_index.py")],
            cwd=КОРЕНЬ_ПРОЕКТА,
        )

    со_ссылкой = sum(1 for р in результаты if р["с_викилинком"] > 0)
    без_ссылки = sum(1 for р in результаты if р["без_викилинка"] > 0 and р["с_викилинком"] == 0)
    print(f"\nИтог: {len(результаты)} компаний упоминают «{ключевое_слово}»")
    print(f"  Уже размечено: {со_ссылкой} | Только голые упоминания: {без_ссылки}")


if __name__ == "__main__":
    главный()
