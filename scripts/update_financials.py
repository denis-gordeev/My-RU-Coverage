def получить_кандидатов_источника(тикер):
    """Возвращает приоритизированный список кандидатов источников финансов для тикера."""
    переопределение = ПЕРЕОПРЕДЕЛЕНИЯ_ИСТОЧНИКОВ_ТИКЕРОВ.get(тикер, {})
    кандидаты = переопределение.get("кандидаты")
    if кандидаты:
        return кандидаты
    return [f"{тикер}{суффикс}" for суффикс in СУФФИКСЫ_РЫНКА_ПО_УМОЛЧАНИЮ]


def определить_суффикс_рынка(символ):
    for суффикс in СУФФИКСЫ_РЫНКА_ПО_УМОЛЧАНИЮ:
        if символ.endswith(суффикс):
            return суффикс
    return ".ME"


def проверить_совпадение_личности(тикер, символ, данные):
    """Отклоняет очевидные совпадения символов (например, тикер T может указывать на компанию AT&T)."""
    переопределение = ПЕРЕОПРЕДЕЛЕНИЯ_ИСТОЧНИКОВ_ТИКЕРОВ.get(тикер, {})
    ключевые_слова = переопределение.get("ключевые_слова_идентификации", [])
    if not ключевые_слова:
        return True

    текст_поиска = " ".join(
        str(данные.get(ключ, "") or "")
        for ключ in ("shortName", "longName", "displayName", "symbol")
    ).lower()

    if not текст_поиска.strip():
        return символ == получить_кандидатов_источника(тикер)[0]

    return any(слово.lower() in текст_поиска for слово in ключевые_слова)


def подготовить_таблицу_отчёта(таблица, суффикс, макс_столбцов):
    if таблица.empty:
        return таблица

    if МЕТКИ_МЕТРИК["выручка"] in таблица.index:
        валидные_столбцы = таблица.columns[таблица.loc[МЕТКИ_МЕТРИК["выручка"]].notna()]
        таблица = таблица[валидные_столбцы]

        таблица = таблица.dropna(axis=1, how="all")

    таблица = таблица[sorted(таблица.columns, reverse=True)]
    без_процентов = [строка for строка in таблица.index if "%" not in строка]
    таблица.loc[без_процентов] = таблица.loc[без_процентов] / 1_000_000
    таблица = таблица.iloc[:, :макс_столбцов]
    return локализовать_подписи_метрик(таблица, суффикс)


def оценить_источник(данные):
    годовых_столбцов = 0 if данные["годовые"] is None else len(данные["годовые"].columns)
    квартальных_столбцов = 0 if данные["квартальные"] is None else len(данные["квартальные"].columns)
    есть_рыночная_кап = 1 if данные.get("рыночная_капитализация") not in (None, "Н/Д") else 0
    есть_сектор = 1 if данные.get("сектор") not in (None, "", "Н/Д", "Не определено") else 0
    return (годовых_столбцов + квартальных_столбцов, есть_рыночная_кап, есть_сектор)


def загрузить_финансы(тикер):
    """Загружает финансовые данные с проверкой приоритета источников."""
    переопределение = ПЕРЕОПРЕДЕЛЕНИЯ_ИСТОЧНИКОВ_ТИКЕРОВ.get(тикер, {})
    лучшие_данные = None
    лучший_результат = (-1, -1, -1)

    for символ in получить_кандидатов_источника(тикер):
        try:
            акция = yf.Ticker(символ)
            инфо = акция.info or {}
            if not проверить_совпадение_личности(тикер, символ, инфо):
                continue

            суффикс = определить_суффикс_рынка(символ)
            df_годовые = подготовить_таблицу_отчёта(
                извлечь_метрики(акция.income_stmt, акция.cashflow), суффикс, 3
            )
            df_квартальные = подготовить_таблицу_отчёта(
                извлечь_метрики(акция.quarterly_income_stmt, акция.quarterly_cashflow),
                суффикс,
                4,
            )

            рыночная_кап = (
                f"{инфо['marketCap'] / 1_000_000:,.0f}"
                if инфо.get("marketCap")
                else "Н/Д"
            )
            стоимость_предприятия = (
                f"{инфо['enterpriseValue'] / 1_000_000:,.0f}"
                if инфо.get("enterpriseValue")
                else "Н/Д"
            )

            мультипликаторы = загрузить_данные_мультипликаторов(инфо)
            профиль_рынка = получить_профиль_рынка(суффикс)
            данные = {
                "годовые": df_годовые,
                "квартальные": df_квартальные,
                "оценка": мультипликаторы,
                "рыночная_капитализация": рыночная_кап,
                "стоимость_предприятия": стоимость_предприятия,
                "сектор": инфо.get("sector") or переопределение.get("сектор", "Н/Д"),
                "отрасль": инфо.get("industry") or переопределение.get("отрасль", "Н/Д"),
                "суффикс": суффикс,
                "единица_измерения": профиль_рынка["единица"],
                "символ_источника": символ,
            }

            if данные["годовые"].empty and данные["квартальные"].empty and рыночная_кап == "Н/Д" and стоимость_предприятия == "Н/Д":
                continue

            оценка_данных = оценить_источник(данные)
            if оценка_данных > лучший_результат:
                лучшие_данные = данные
                лучший_результат = оценка_данных
        except Exception:
            continue
    return лучшие_данные


def таблица_в_формат_markdown(таблица):
    """Форматирует таблицу данных (DataFrame) в формат markdown с точностью .2f, затем заменяет пропуски (NaN) на -."""
    текст_мд = таблица.to_markdown(floatfmt=".2f")
    текст_мд = текст_мд.replace(" nan ", " - ")
    текст_мд = текст_мд.replace(" nan|", " -|")
    текст_мд = текст_мд.replace("|nan ", "|- ")
    текст_мд = re.sub(r'\bnan\b', '-', текст_мд)
    return текст_мд


def построить_финансовую_секцию(данные):
    метка_единицы = данные.get("единица_измерения", "млн руб.")
    секция = f"{ЗАГОЛОВОК_СЕКЦИИ_ФИНАНСОВ} (единицы: {метка_единицы}, маржа указана в %)\n"

    мультипликаторы = данные.get("оценка", {})
    if мультипликаторы:
        секция += построить_таблицу_мультипликаторов(мультипликаторы) + "\n\n"

    секция += f"{ЗАГОЛОВОК_СЕКЦИИ_ГОДОВЫХ}\n"
    if данные["годовые"] is not None and not данные["годовые"].empty:
        секция += таблица_в_формат_markdown(данные["годовые"]) + "\n\n"
    else:
        секция += "Нет доступных данных.\n\n"
    секция += f"{ЗАГОЛОВОК_СЕКЦИИ_КВАРТАЛЬНЫХ}\n"
    if данные["квартальные"] is not None and not данные["квартальные"].empty:
        секция += таблица_в_формат_markdown(данные["квартальные"]) + "\n"
    else:
        секция += "Нет доступных данных.\n"
    return секция


def обновить_файл(путь, тикер, пробный_запуск=False):
    with open(путь, "r", encoding="utf-8") as ф:
        содержимое = ф.read()

    данные = загрузить_финансы(тикер)
    if данные is None:
        print(f"  {тикер}: пропуск (источник данных не вернул данные)")
        return False

    новая_секция = построить_финансовую_секцию(данные)

    if re.search(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["финансовый_обзор"], содержимое):
        новое_содержимое = re.sub(rf"{РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ['финансовый_обзор']}.*", новая_секция, содержимое, flags=re.DOTALL)
    else:
        новое_содержимое = содержимое.rstrip() + "\n\n" + новая_секция

    # Обновляем метаданные
    новое_содержимое = обновить_метаданные(
        новое_содержимое,
        данные.get("рыночная_капитализация"),
        данные.get("стоимость_предприятия"),
        данные.get("единица_измерения", "млн руб."),
    )
    новое_содержимое = обновить_классификацию_компании(
        новое_содержимое,
        данные.get("сектор"),
        данные.get("отрасль"),
    )

    if пробный_запуск:
        print(f"  {тикер}: черновое обновление ({данные['символ_источника']})")
        return True

    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(новое_содержимое)
    print(f"  {тикер}: обновлено ({данные['символ_источника']})")
    return True


