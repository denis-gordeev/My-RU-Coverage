def получить_ряд(таблица, ключи):
    for ключ in ключи:
        if ключ in таблица.index:
            return таблица.loc[ключ]
    return pd.Series(dtype=float)


def вычислить_маржу(числитель, знаменатель):
    if знаменатель.empty or числитель.empty:
        return pd.Series(dtype=float)
    результат = (числитель / знаменатель) * 100
    результат = результат.replace([float("inf"), float("-inf")], float("nan"))
    return результат


def вычислить_управленческие_расходы(отчёт_о_прибылях):
    """Получает административные расходы, при отсутствии — вычисляет как управленческие и коммерческие расходы (УКР) − коммерческие расходы."""
    административные = получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["общехозяйственные_расходы"])
    коммерческие = получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["коммерческие_расходы"])
    управленческие_и_коммерческие = получить_ряд(отчёт_о_прибылях, ["Selling General And Administration"])

    if административные.empty and not управленческие_и_коммерческие.empty and not коммерческие.empty:
        return управленческие_и_коммерческие - коммерческие
    elif not административные.empty and not управленческие_и_коммерческие.empty:
        производные = управленческие_и_коммерческие - коммерческие
        return административные.fillna(производные)
    return административные


def извлечь_метрики(отчёт_о_прибылях, денежный_поток):
    if отчёт_о_прибылях.empty and денежный_поток.empty:
        return pd.DataFrame()

    данные = {
        МЕТКИ_МЕТРИК["выручка"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["выручка"]),
        МЕТКИ_МЕТРИК["валовая_прибыль"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["валовая_прибыль"]),
        МЕТКИ_МЕТРИК["валовая_маржа"]: вычислить_маржу(
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["валовая_прибыль"]),
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["выручка"]),
        ),
        МЕТКИ_МЕТРИК["коммерческие_расходы"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["коммерческие_расходы"]),
        МЕТКИ_МЕТРИК["расходы_ниокр"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["расходы_ниокр"]),
        МЕТКИ_МЕТРИК["общехозяйственные_расходы"]: вычислить_управленческие_расходы(отчёт_о_прибылях),
        МЕТКИ_МЕТРИК["операционная_прибыль"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["операционная_прибыль"]),
        МЕТКИ_МЕТРИК["операционная_маржа"]: вычислить_маржу(
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["операционная_прибыль"]),
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["выручка"]),
        ),
        МЕТКИ_МЕТРИК["чистая_прибыль"]: получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["чистая_прибыль"]),
        МЕТКИ_МЕТРИК["чистая_маржа"]: вычислить_маржу(
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["чистая_прибыль"]),
            получить_ряд(отчёт_о_прибылях, КЛЮЧИ_МЕТРИК["выручка"]),
        ),
        МЕТКИ_МЕТРИК["операционный_поток"]: получить_ряд(денежный_поток, КЛЮЧИ_МЕТРИК["операционный_поток"]),
        МЕТКИ_МЕТРИК["инвестиционный_поток"]: получить_ряд(денежный_поток, КЛЮЧИ_МЕТРИК["инвестиционный_поток"]),
        МЕТКИ_МЕТРИК["финансовый_поток"]: получить_ряд(денежный_поток, КЛЮЧИ_МЕТРИК["финансовый_поток"]),
        МЕТКИ_МЕТРИК["капитальные_затраты"]: получить_ряд(денежный_поток, КЛЮЧИ_МЕТРИК["капитальные_затраты"]),
    }

    # Выводим капитальные затраты из свободного денежного потока при отсутствии: капзатраты = свободный поток − операционный поток (отрицательный)
    капзатраты = данные[МЕТКИ_МЕТРИК["капитальные_затраты"]]
    операционный_поток = данные[МЕТКИ_МЕТРИК["операционный_поток"]]
    свободный_поток = получить_ряд(денежный_поток, ["Free Cash Flow"])
    if not капзатраты.empty and not операционный_поток.empty and not свободный_поток.empty:
        производные_капзатраты = свободный_поток - операционный_поток
        данные[МЕТКИ_МЕТРИК["капитальные_затраты"]] = капзатраты.fillna(производные_капзатраты)
    elif капзатраты.empty and not операционный_поток.empty and not свободный_поток.empty:
        данные[МЕТКИ_МЕТРИК["капитальные_затраты"]] = свободный_поток - операционный_поток

    таблица = pd.DataFrame(данные).T
    # Очищаем заголовки столбцов: убираем временную часть из формата даты-времени
    таблица.columns = [
        столбец.strftime("%Y-%m-%d") if hasattr(столбец, "strftime") else str(столбец)
        for столбец in таблица.columns
    ]
    return таблица


