"""
build_wikilink_index.py — Пересобирает WIKILINKS.md по всем карточкам эмитентов.

Использование:
    python scripts/build_wikilink_index.py

Сканирует все `.md` в `Pilot_Reports/` и собирает категоризированный индекс
всех `[[викилинки]]` с числом упоминаний. Запускается после обновления
карточек, тем или связей.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import (
    извлечь_викилинки, классифицировать_викилинк,
)

ДИРЕКТОРИЯ_ОТЧЁТОВ = os.path.join(os.path.dirname(__file__), "..", "Pilot_Reports")
ФАЙЛ_ВЫВОДА = os.path.join(os.path.dirname(__file__), "..", "WIKILINKS.md")


def собрать_викилинки():
    """Возвращает словарь `{викилинк: число_упоминаний}` по всем отчётам."""
    викилинки = {}
    for корень, папки, файлы in os.walk(ДИРЕКТОРИЯ_ОТЧЁТОВ):
        for файл in файлы:
            if not файл.endswith(".md"):
                continue
            with open(os.path.join(корень, файл), "r", encoding="utf-8") as дескриптор:
                содержимое = дескриптор.read()
            for викилинк in извлечь_викилинки(содержимое):
                викилинки[викилинк] = викилинки.get(викилинк, 0) + 1
    return викилинки


def категоризировать(викилинки):
    """Разбивает викилинки по смысловым категориям."""
    технологии = {}
    материалы = {}
    применения = {}
    компании_российские = {}
    компании_иностранные = {}

    for имя, количество in викилинки.items():
        категория = классифицировать_викилинк(имя)
        if категория == "технология":
            технологии[имя] = количество
        elif категория == "материал":
            материалы[имя] = количество
        elif категория == "конечный_рынок":
            применения[имя] = количество
        elif категория == "российская_компания" and количество >= 2:
            компании_российские[имя] = количество
        elif категория == "иностранная_компания" and количество >= 2:
            компании_иностранные[имя] = количество

    return технологии, материалы, применения, компании_иностранные, компании_российские


def построить_секцию(заголовок, элементы, лимит=None):
    """Строит раздел в формате МД из словаря `{имя: счётчик}`."""
    строки = []
    отсортированные = sorted(элементы.items(), key=lambda пара: -пара[1])
    if лимит:
        показанные = отсортированные[:лимит]
        метка_итого = f" ({len(элементы)} всего, показаны первые {лимит})"
    else:
        показанные = отсортированные
        метка_итого = f" ({len(элементы)})"

    строки.append(f"## {заголовок}{метка_итого}")
    строки.append("")
    for имя, количество in показанные:
        строки.append(f"- [[{имя}]] ({количество})")
    строки.append("")
    return строки


def главный():
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8")

    викилинки = собрать_викилинки()
    тех, мат, прим, ин, лок = категоризировать(викилинки)

    строки = [
        "# Индекс викилинков",
        "",
        f"> **{len(викилинки)} уникальных викилинков** по всем отчётам. Файл генерируется автоматически.",
        f"> Пересобрать: `python scripts/build_wikilink_index.py`",
        "",
        "---",
        "",
    ]

    строки.extend(построить_секцию("Технологии и стандарты", тех))
    строки.extend(построить_секцию("Материалы и сырьё", мат))
    строки.extend(построить_секцию("Конечные рынки и применения", прим))
    строки.extend(построить_секцию("Иностранные компании", ин, лимит=200))
    строки.extend(построить_секцию("Российские компании", лок, лимит=300))

    with open(ФАЙЛ_ВЫВОДА, "w", encoding="utf-8") as ф:
        ф.write("\n".join(строки))

    print(f"Сгенерирован WIKILINKS.md: {len(викилинки)} уникальных викилинков")
    print(f"  Технологии: {len(тех)}")
    print(f"  Материалы: {len(мат)}")
    print(f"  Применения: {len(прим)}")
    print(f"  Иностранные компании: {len(ин)}")
    print(f"  Российские компании: {len(лок)}")


if __name__ == "__main__":
    главный()
