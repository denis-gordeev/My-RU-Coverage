"""
add_ticker.py — Генерация отчёта нового тикера с финансовыми данными и базовой структурой.

Создаёт новый .md файл в Pilot_Reports/{сектор}/ с:
- Заголовком с викилинком на название компании
- Метаданными (сектор, отрасль, рыночная кап., стоимость предприятия)
- Секциями-заглушками для обогащения
- Финансовыми таблицами из yfinance (годовые 3г + квартальные 4кв)

Использование:
  python scripts/add_ticker.py GAZP Газпром                         # Автоопределение сектора
  python scripts/add_ticker.py GAZP Газпром --сектор Энергетика      # Указать сектор

После генерации используйте update_enrichment.py для добавления описаний деятельности.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import (
    найти_файлы_тикеров, ДИРЕКТОРИЯ_ОТЧЁТОВ, КОРЕНЬ_ПРОЕКТА,
    ЗАГОЛОВОК_СЕКЦИИ_ОПИСАНИЯ, ЗАГОЛОВОК_СЕКЦИИ_ЦЕПОЧКИ, ЗАГОЛОВОК_СЕКЦИИ_КЛИЕНТОВ,
    ЗАГОЛОВОК_СЕКЦИИ_ФИНАНСОВ, ЗАГОЛОВОК_СЕКЦИИ_ГОДОВЫХ, ЗАГОЛОВОК_СЕКЦИИ_КВАРТАЛЬНЫХ,
)

# Импорт загрузчика финансовых данных
from update_financials import загрузить_финансы, построить_финансовую_секцию


def сгенерировать_отчёт(тикер, название, сектор=None, отрасль=None):
    """Генерирует полный файл отчёта для нового тикера."""
    финансовые_данные = загрузить_финансы(тикер)

    if финансовые_данные:
        if not сектор:
            сектор = финансовые_данные.get("сектор", "Не определено")
        if not отрасль:
            отрасль = финансовые_данные.get("отрасль", "Не определено")
        рыночная_кап = финансовые_данные.get("рыночная_капитализация") or "Н/Д"
        стоимость_предпр = финансовые_данные.get("стоимость_предприятия") or "Н/Д"
        метка_единицы = финансовые_данные.get("единица_измерения", "млн руб.")
        секция_финансов = построить_финансовую_секцию(финансовые_данные)
    else:
        if not сектор:
            сектор = "Не определено"
        if not отрасль:
            отрасль = "Не определено"
        рыночная_кап = "Н/Д"
        стоимость_предпр = "Н/Д"
        метка_единицы = "млн руб."
        секция_финансов = (
            f"{ЗАГОЛОВОК_СЕКЦИИ_ФИНАНСОВ} (единицы: {метка_единицы}, маржа указана в %)\n"
            f"{ЗАГОЛОВОК_СЕКЦИИ_ГОДОВЫХ}\nНет доступных данных.\n\n"
            f"{ЗАГОЛОВОК_СЕКЦИИ_КВАРТАЛЬНЫХ}\nНет доступных данных.\n"
        )

    содержимое = f"""# {тикер} - [[{название}]]

{ЗАГОЛОВОК_СЕКЦИИ_ОПИСАНИЯ}
**Сектор:** {сектор}
**Отрасль:** {отрасль}
**Рыночная капитализация:** {рыночная_кап} {метка_единицы}
**Стоимость предприятия (EV):** {стоимость_предпр} {метка_единицы}

*(Нужно обогащение: заполните описание через `update_enrichment.py`.)*

{ЗАГОЛОВОК_СЕКЦИИ_ЦЕПОЧКИ}
*(Нужно обогащение.)*

{ЗАГОЛОВОК_СЕКЦИИ_КЛИЕНТОВ}
*(Нужно обогащение.)*

{секция_финансов}"""

    return содержимое, сектор


def очистить_имя_папки(название):
    """Очищает название сектора для использования в имени папки."""
    # Заменяем символы, проблемные для путей Windows
    return re.sub(r'[<>:"/\\|?*]', "", название).strip()


def главный():
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    аргументы = sys.argv[1:]

    if not аргументы or аргументы[0] in {"-h", "--help"}:
        print("Использование:")
        print("  python scripts/add_ticker.py <тикер> <название>")
        print("  python scripts/add_ticker.py <тикер> <название> --сектор <сектор>")
        return

    # Разбор аргументов
    тикер = аргументы[0]
    название = аргументы[1] if len(аргументы) > 1 else "Без названия"

    сектор = None
    if "--сектор" in аргументы:
        индекс = аргументы.index("--сектор")
        сектор = " ".join(аргументы[индекс + 1 :])

    # Проверяем, не существует ли уже тикер
    существующие = найти_файлы_тикеров([тикер])
    if существующие:
        print(f"Тикер {тикер} уже существует: {существующие[тикер]}")
        print("Для обновления используйте update_financials.py или update_enrichment.py.")
        return

    print(f"Создаю карточку для {тикер} ({название})...")
    содержимое, определённый_сектор = сгенерировать_отчёт(тикер, название, сектор)

    # Определяем папку вывода
    имя_папки = очистить_имя_папки(сектор or определённый_сектор)
    директория_вывода = os.path.join(ДИРЕКТОРИЯ_ОТЧЁТОВ, имя_папки)
    os.makedirs(директория_вывода, exist_ok=True)

    # Записываем файл
    имя_файла = f"{тикер}_{название}.md"
    путь_к_файлу = os.path.join(директория_вывода, имя_файла)
    with open(путь_к_файлу, "w", encoding="utf-8") as ф:
        ф.write(содержимое)

    print(f"Создан файл: {путь_к_файлу}")
    print(f"Сектор: {имя_папки}")
    print("\nДальше: используйте update_enrichment.py, чтобы добавить описание деятельности, цепочку поставок и контрагентов.")


if __name__ == "__main__":
    главный()
