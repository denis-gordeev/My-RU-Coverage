#!/usr/bin/env python3
"""Проверка качества всех российских (MOEX) отчётов в Pilot_Reports/."""
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ДИРЕКТОРИЯ_ОТЧЁТОВ = КОРЕНЬ / "Pilot_Reports"
УСТАРЕВШИЕ_ТЕМАТИЧЕСКИЕ_МЕТКИ = {
    "HBM", "CoWoS", "CPO", "EUV", "VCSEL",
}
РЕГЕКС_ИЕРОГЛИФОВ = re.compile(r"[\u4e00-\u9fff]")

def проверить_файл(путь_к_файлу):
    """Вернуть список замечаний по одному отчёту."""
    замечания = []
    содержимое = путь_к_файлу.read_text(encoding="utf-8")

    # 1. Ищем слишком общие викилинк-сущности.
    викилинки = re.findall(r"\[\[([^\]]+)\]\]", содержимое)
    отраслевые_аббревиатуры = {
        "СПГ", "АЗС", "МСБ", "ОРЭМ", "ДПМ", "ФСТ", "СУЭК", "АТС", "ЖКХ",
        "КОМ", "РСВ", "НЛМК", "ММК", "МТС", "ВТБ", "Сбер", "Тева", "ФСБ",
        "Циан", "Юла", "ЕГРН", "ПИК", "Озон", "РЖД", "САПР", "ЧПУ",
        "ФосАгро", "Лукойл", "Газпром", "Роснефть", "Сургутнефтегаз",
        "Татнефть", "Башнефть", "НОВАТЭК", "РусГидро", "Аэрофлот",
        "Магнит", "Пятерочка", "Перекресток", "Дикси", "Лента",
        "MOEX", "ЦБ", "ФАС", "Минцифры", "44-ФЗ", "223-ФЗ",
    }
    шаблоны_общих_сущностей = [
        r"^компания$",
        r"^предприятие$",
        r"^организация$",
        r"^сервис$",
        r"^технологии?$",
        r"^цифровы[е|ой]$",
        r"^производств[о|а|у]$",
        r"^рынок$",
        r"^инфраструктур[а|ы]$",
        r"^материалы?$",
        r"^продукци[я|и]$",
        r"^оборудовани[е|я]$",
        r"^решени[я|е]$",
        r"^поставщик[и|ов]?$",
        r"^клиент[ы|ов]?$",
    ]
    общие_викилинки = []
    for вл in викилинки:
        очищенный_вл = вл.strip()
        if очищенный_вл in отраслевые_аббревиатуры:
            continue
        if re.match(r"^[A-ZА-ЯЁ]{2,6}$", очищенный_вл):
            continue
        основа = очищенный_вл.split("|")[0].strip()
        for шаблон in шаблоны_общих_сущностей:
            if re.match(шаблон, основа, re.IGNORECASE):
                общие_викилинки.append(вл)
                break
    if общие_викилинки:
        замечания.append(f"Слишком общие викилинк-сущности: {', '.join(общие_викилинки)}")

    # 2. Проверяем размер секции про клиентов и поставщиков.
    совпадение_клиентов = re.search(r"## Ключевые клиенты? и поставщики?", содержимое)
    if совпадение_клиентов:
        секция = содержимое[совпадение_клиентов.end():]
        следующая_секция = re.search(r"\n## ", секция)
        if следующая_секция:
            секция = секция[:следующая_секция.start()]
        строки = [строка for строка in секция.strip().split("\n") if строка.strip()]
        if len(строки) < 4:
            замечания.append(f"Слишком короткий блок клиентов/поставщиков: {len(строки)} строк")

    # 3. Проверяем обязательные разделы.
    обязательные = [
        "## Описание деятельности",
        "## Положение в цепочке поставок",
        "## Ключевые клиенты и поставщики",
        "## Финансовый обзор",
    ]
    for секция in обязательные:
        if секция not in содержимое:
            замечания.append(f"Отсутствует обязательный раздел: {секция}")

    # 4. Проверяем минимальное число викилинков.
    if len(викилинки) < 10:
        замечания.append(f"Недостаточно викилинков: {len(викилинки)} (нужно >= 10)")

    # 5. Ловим остаточные устаревшие темы и китайские сущности в российском корпусе.
    устаревшие_совпадения = []
    for вл in викилинки:
        основа = вл.split("|")[0].strip()
        if основа in УСТАРЕВШИЕ_ТЕМАТИЧЕСКИЕ_МЕТКИ or РЕГЕКС_ИЕРОГЛИФОВ.search(основа):
            устаревшие_совпадения.append(основа)
    if устаревшие_совпадения:
        замечания.append(
            "Обнаружены устаревшие сущности вне российского контура: "
            + ", ".join(sorted(set(устаревшие_совпадения)))
        )

    return замечания


