#!/usr/bin/env python3
"""
moex_status.py — Статус-сводка по покрытию MOEX.

Выводит краткую сводку: число российских карточек, статус проверки,
число тем и следующая очередь тикеров из MOEX ISS.

Использование:
    python scripts/moex_status.py
    python scripts/moex_status.py --json
"""

import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import найти_файлы_тикеров, настроить_вывод, ШАБЛОН_ТИКЕРА, создать_русский_парсер

КОРЕНЬ = Path(__file__).resolve().parents[1]
ДИРЕКТОРИЯ_ОТЧЁТОВ = КОРЕНЬ / "Pilot_Reports"
ДИРЕКТОРИЯ_ТЕМ = КОРЕНЬ / "themes"


def посчитать_отчёты():
    отчёты = найти_файлы_тикеров()
    по_сектору = {}
    for тикер, путь_к_файлу in отчёты.items():
        сектор = os.path.basename(os.path.dirname(путь_к_файлу))
        по_сектору.setdefault(сектор, []).append(тикер)
    return len(отчёты), по_сектору


def посчитать_темы():
    if not ДИРЕКТОРИЯ_ТЕМ.exists():
        return 0
    return len([f for f in ДИРЕКТОРИЯ_ТЕМ.iterdir() if f.suffix == ".md" and f.name != "README.md"])


def проверить_аудит():
    всего = 0
    чистые = 0
    число_замечаний = 0
    for подпапка in sorted(ДИРЕКТОРИЯ_ОТЧЁТОВ.iterdir()):
        if not подпапка.is_dir():
            continue
        for мд_файл in sorted(подпапка.glob("*.md")):
            всего += 1
            содержимое = мд_файл.read_text(encoding="utf-8")
            викилинки = re.findall(r"\[\[([^\]]+)\]\]", содержимое)
            есть_обязательные = all(
                секция in содержимое
                for секция in [
                    "## Описание деятельности",
                    "## Положение в цепочке поставок",
                    "## Ключевые клиенты и поставщики",
                    "## Финансовый обзор",
                ]
            )
            есть_метаданные = all(
                re.search(шаблон, содержимое)
                for шаблон in [
                    r"\*\*Сектор:\*\*",
                    r"\*\*Отрасль:\*\*",
                    r"\*\*Рыночная капитализация:\*\*",
                ]
            )
            минимум_викилинков = len(викилинки) >= 10
            if есть_обязательные and есть_метаданные and минимум_викилинков:
                чистые += 1
            else:
                число_замечаний += 1
    return всего, чистые, число_замечаний


def получить_сводку_очереди():
    try:
        from moex_blue_chip_queue import построить_отчёт, КОДЫ_ИНДЕКСОВ_ПО_УМОЛЧАНИЮ
        отчёт = построить_отчёт(КОДЫ_ИНДЕКСОВ_ПО_УМОЛЧАНИЮ)
        очередь = отчёт.get("следующая_очередь", [])
        первые_5 = [
            {"тикер": элемент["тикер"], "название": элемент["название"]}
            for элемент in очередь[:5]
        ]
        return len(очередь), первые_5, отчёт.get("дата_торгов")
    except Exception as ошибка:
        return None, None, None, str(ошибка)


def main():
    настроить_вывод()
    парсер = создать_русский_парсер(description="Статус-сводка по покрытию MOEX")
    парсер.add_argument("--json", action="store_true", help="Вывести в формате JSON")
    аргументы = парсер.parse_args()

    число_отчётов, по_сектору = посчитать_отчёты()
    число_тем = посчитать_темы()
    всего_аудит, чистых_аудит, замечаний_аудит = проверить_аудит()
    результат_очереди = получить_сводку_очереди()

    if len(результат_очереди) == 4:
        длина_очереди, очередь_первые_5, дата_очереди = None, None, None
        ошибка_очереди = результат_очереди[3]
    else:
        длина_очереди, очередь_первые_5, дата_очереди = результат_очереди
        ошибка_очереди = None

    доля_аудита = (чистых_аудит / всего_аудит * 100) if всего_аудит > 0 else 0

    сводка = {
        "отчёты": число_отчётов,
        "секторы": len(по_сектору),
        "по_сектору": {сектор: len(тикеры) for сектор, тикеры in sorted(по_сектору.items())},
        "темы": число_тем,
        "проверка": {
            "всего": всего_аудит,
            "чистых": чистых_аудит,
            "замечаний": замечаний_аудит,
            "доля_%": round(доля_аудита, 1),
        },
        "очередь": {
            "непокрытых": длина_очереди,
            "дата": дата_очереди,
            "первые_5": очередь_первые_5,
        },
    }

    if ошибка_очереди:
        сводка["очередь"]["ошибка"] = ошибка_очереди

    if аргументы.json:
        print(json.dumps(сводка, ensure_ascii=False, indent=2))
        return

    print("=" * 50)
    print("  Статус покрытия MOEX")
    print("=" * 50)
    print()
    print(f"  Карточки:       {число_отчётов}")
    print(f"  Секторы:        {len(по_сектору)}")
    print(f"  Темы:           {число_тем}")
    print()
    print(f"  Проверка:      {чистых_аудит}/{всего_аудит} ({доля_аудита:.0f}%) проходят")
    if замечаний_аудит:
        print(f"                  {замечаний_аудит} с замечаниями")
    print()

    if длина_очереди is not None:
        print(f"  Очередь MOEX:   {длина_очереди} непокрытых ({дата_очереди})")
        if очередь_первые_5:
            print("  Следующие:")
            for элемент in очередь_первые_5:
                print(f"    - {элемент['тикер']} ({элемент['название']})")
    else:
        print(f"  Очередь MOEX:   недоступна ({ошибка_очереди})")

    print()
    print("  Секторы:")
    for сектор, тикеры in sorted(по_сектору.items(), key=lambda x: -len(x[1])):
        print(f"    {сектор}: {len(тикеры)}")
    print()
    print("=" * 50)


if __name__ == "__main__":
    main()
