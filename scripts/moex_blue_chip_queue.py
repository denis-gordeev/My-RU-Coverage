"""
moex_blue_chip_queue.py — Проверка официальных корзин MOEX через ISS.

Показывает актуальный состав одного или нескольких индексов MOEX и отмечает,
для каких тикеров в `Pilot_Reports/` ещё нет российских карточек покрытия.
По умолчанию объединяет полностью покрытую корзину крупнейших акций (`MOEXBC`)
и более широкий ликвидный индекс (`MOEXBMI`), чтобы сформировать следующую
очередь для исследования.

Использование:
  python scripts/moex_blue_chip_queue.py
  python scripts/moex_blue_chip_queue.py --индекс MOEXBC
  python scripts/moex_blue_chip_queue.py --индекс MOEXBMI --дата 2026-04-03
  python scripts/moex_blue_chip_queue.py --json
"""

import json
import os
import sys
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import urlopen

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import найти_файлы_тикеров, настроить_вывод, создать_русский_парсер

АДРЕС_ISS = "https://iss.moex.com/iss/statistics/engines/stock/markets/index/analytics/MOEXBC/constituents.json"
КОДЫ_ИНДЕКСОВ_ПО_УМОЛЧАНИЮ = ["MOEXBC", "MOEXBMI"]
МЕТКИ_ИНДЕКСОВ = {
    "MOEXBC": "Индекс крупнейших акций",
    "MOEXBMI": "Индекс широкого рынка",
    "MOEXOG": "Нефть и газ",
    "MOEXTL": "Телекоммуникации",
    "MOEXFN": "Финансы",
    "MOEXMM": "Металлы и добыча",
    "MOEXEU": "Электроэнергетика",
    "MOEXCN": "Потребительский сектор",
    "MOEXCH": "Химия и нефтехимия",
}


def загрузить_состав(код_индекса, дата_торгов=None):
    параметры = {"iss.meta": "off"}
    if дата_торгов:
        параметры["date"] = дата_торгов

    адрес_iss = АДРЕС_ISS.replace("/MOEXBC/", f"/{код_индекса}/")
    адрес = f"{адрес_iss}?{urlencode(параметры)}"
    with urlopen(адрес, timeout=20) as ответ:
        данные_ответа = json.load(ответ)

    столбцы = данные_ответа["analytics"]["columns"]
    строки = данные_ответа["analytics"]["data"]
    элементы = [dict(zip(столбцы, строка)) for строка in строки]
    элементы.sort(key=lambda элемент: элемент.get("weight") or 0, reverse=True)
    for ранг, элемент in enumerate(элементы, start=1):
        элемент["rank"] = ранг
    return элементы


def _перевести_элемент(элемент):
    return {
        "тикер": элемент.get("ticker"),
        "название": элемент.get("shortnames"),
        "вес": элемент.get("weight"),
        "ранг": элемент.get("rank"),
        "дата_торгов": элемент.get("tradedate"),
    }


def построить_отчёт_по_индексу(код_индекса, элементы):
    покрытые = set(найти_файлы_тикеров().keys())
    отсутствующие = [элемент for элемент in элементы if элемент["ticker"] not in покрытые]
    отчёт = {
        "код_индекса": код_индекса,
        "название_индекса": МЕТКИ_ИНДЕКСОВ.get(код_индекса, код_индекса),
        "дата_торгов": элементы[0]["tradedate"] if элементы else None,
        "количество": len(элементы),
        "покрыто": len(элементы) - len(отсутствующие),
        "отсутствует": len(отсутствующие),
        "состав": [_перевести_элемент(э) for э in элементы],
        "отсутствующие": [_перевести_элемент(э) for э in отсутствующие],
    }
    return отчёт


def построить_отчёт(коды_индексов, дата_торгов=None):
    отчёты_по_индексам = []
    агрегированные_отсутствующие = {}
    даты_торгов = []

    for код_индекса in коды_индексов:
        элементы = загрузить_состав(код_индекса, дата_торгов)
        отчёт_по_индексу = построить_отчёт_по_индексу(код_индекса, элементы)
        отчёты_по_индексам.append(отчёт_по_индексу)
        if отчёт_по_индексу["дата_торгов"]:
            даты_торгов.append(отчёт_по_индексу["дата_торгов"])

        for элемент in отчёт_по_индексу["отсутствующие"]:
            тикер = элемент["тикер"]
            существующий = агрегированные_отсутствующие.get(тикер)
            if существующий is None:
                агрегированные_отсутствующие[тикер] = {
                    "тикер": тикер,
                    "название": элемент["название"],
                    "индексы": [код_индекса],
                    "лучший_ранг": элемент["ранг"],
                    "максимальный_вес": элемент["вес"],
                }
                continue

            существующий["индексы"].append(код_индекса)
            существующий["лучший_ранг"] = min(существующий["лучший_ранг"], элемент["ранг"])
            существующий["максимальный_вес"] = max(существующий["максимальный_вес"], элемент["вес"])

    следующая_очередь = sorted(
        агрегированные_отсутствующие.values(),
        key=lambda элемент: (элемент["лучший_ранг"], -элемент["максимальный_вес"], элемент["тикер"]),
    )

    return {
        "запрошенные_индексы": коды_индексов,
        "дата_торгов": max(даты_торгов) if даты_торгов else None,
        "отчёты": отчёты_по_индексам,
        "следующая_очередь": следующая_очередь,
    }


def вывести_отчёт(отчёт):
    for отчёт_по_индексу in отчёт["отчёты"]:
        print(
            f"{отчёт_по_индексу['код_индекса']} ({отчёт_по_индексу['название_индекса']}) на "
            f"{отчёт_по_индексу['дата_торгов']}: {отчёт_по_индексу['количество']} бумаг | "
            f"покрыто: {отчёт_по_индексу['покрыто']} | отсутствует: {отчёт_по_индексу['отсутствует']}"
        )
        print("")
        print("Текущий состав:")
        for элемент in отчёт_по_индексу["состав"]:
            print(
                f"  #{элемент['ранг']:<2} {элемент['тикер']:<6} {элемент['название']:<20} "
                f"{элемент['вес']:>5.2f}%"
            )

        print("")
        if отчёт_по_индексу["отсутствующие"]:
            print("Без российской карточки:")
            for элемент in отчёт_по_индексу["отсутствующие"]:
                print(
                    f"  - #{элемент['ранг']:<2} {элемент['тикер']} ({элемент['название']}), "
                    f"вес {элемент['вес']:.2f}%"
                )
        else:
            print("Все текущие бумаги этого индекса уже покрыты российскими карточками.")
        print("")

    if отчёт["следующая_очередь"]:
        print("Следующая агрегированная очередь покрытия:")
        for элемент in отчёт["следующая_очередь"]:
            индексы = ", ".join(элемент["индексы"])
            print(
                f"  - #{элемент['лучший_ранг']:<2} {элемент['тикер']} ({элемент['название']}), "
                f"индексы: {индексы}, макс. вес {элемент['максимальный_вес']:.2f}%"
            )
    else:
        print("Объединённая очередь индексов уже полностью покрыта российскими карточками.")


def main():
    настроить_вывод()
    parser = создать_русский_парсер(
        description=(
            "Проверить актуальный состав официальных корзин MOEX через MOEX ISS "
            "и собрать следующую очередь покрытия."
        )
    )
    parser.add_argument("--дата", help="Дата состава в формате YYYY-MM-DD")
    parser.add_argument(
        "--индекс",
        dest="индексы",
        action="append",
        help=(
            "Код индекса MOEX ISS. Можно повторять несколько раз; по умолчанию "
            "используются MOEXBC и MOEXBMI."
        ),
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Вывести результат в JSON",
    )
    args = parser.parse_args()
    коды_индексов = args.индексы or КОДЫ_ИНДЕКСОВ_ПО_УМОЛЧАНИЮ

    try:
        отчёт = построить_отчёт(коды_индексов, args.дата)
    except HTTPError as ошибка:
        print(f"Ошибка HTTP при запросе MOEX ISS: {ошибка}", file=sys.stderr)
        sys.exit(1)
    except URLError as ошибка:
        print(f"Сетевой сбой при запросе MOEX ISS: {ошибка}", file=sys.stderr)
        sys.exit(1)

    if args.json:
        print(json.dumps(отчёт, ensure_ascii=False, indent=2))
        return

    вывести_отчёт(отчёт)


if __name__ == "__main__":
    main()
