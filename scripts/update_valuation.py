"""
update_valuation.py — Обновление ТОЛЬКО оценочных мультипликаторов в отчётах тикеров.

Гораздо быстрее, чем update_financials.py, так как загружает только stock.info (без финансовых отчётов).
Обновляет: P/E (за 12 мес.), Прогнозный P/E, P/S, P/B, EV/EBITDA, цену акции и даты периодов.
Сохраняет всё остальное содержимое, включая финансовые таблицы.

Использование:
  python scripts/update_valuation.py                        # ВСЕ тикеры
  python scripts/update_valuation.py SBER                   # Один тикер
  python scripts/update_valuation.py SBER GAZP LKOH         # Несколько тикеров
  python scripts/update_valuation.py --сектор Энергетика    # По сектору
  python scripts/update_valuation.py --пробный-запуск SBER  # Предпросмотр без записи
"""

import os
import re
import sys
import time

import yfinance as yf

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import (
    найти_файлы_тикеров, разобрать_аргументы_области, настроить_вывод,
    загрузить_данные_мультипликаторов, построить_таблицу_мультипликаторов, обновить_метаданные,
    СУФФИКСЫ_РЫНКА_ПО_УМОЛЧАНИЮ, получить_профиль_рынка,
    РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ,
)


def загрузить_оценку(тикер):
    """Загружает только оценочные мультипликаторы. Пробует суффиксы в приоритетном порядке."""
    for суффикс in СУФФИКСЫ_РЫНКА_ПО_УМОЛЧАНИЮ:
        try:
            акция = yf.Ticker(f"{тикер}{суффикс}")
            инфо = акция.info
            if not инфо or not инфо.get("currentPrice"):
                continue

            мультипликаторы = загрузить_данные_мультипликаторов(инфо)

            рыночная_кап = (
                f"{инфо['marketCap'] / 1_000_000:,.0f}"
                if инфо.get("marketCap")
                else None
            )
            стоимость_предприятия = (
                f"{инфо['enterpriseValue'] / 1_000_000:,.0f}"
                if инфо.get("enterpriseValue")
                else None
            )
            профиль_рынка = получить_профиль_рынка(суффикс)
            return {
                "оценка": мультипликаторы,
                "рыночная_капитализация": рыночная_кап,
                "стоимость_предприятия": стоимость_предприятия,
                "суффикс": суффикс,
                "единица_измерения": профиль_рынка["единица"],
            }
        except Exception:
            continue
    return None


def обновить_файл(путь, тикер, пробный_запуск=False):
    """Обновляет только раздел оценки в файле тикера."""
    with open(путь, "r", encoding="utf-8") as ф:
        содержимое = ф.read()

    данные = загрузить_оценку(тикер)
    if данные is None:
        print(f"  {тикер}: пропуск (нет данных)")
        return False

    новая_таблица = построить_таблицу_мультипликаторов(данные["оценка"])

    if re.search(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["оценочные_мультипликаторы"], содержимое):
        содержимое = re.sub(
            rf"{РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ['оценочные_мультипликаторы']}.*?(?=\n{РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ['годовые_показатели']})",
            новая_таблица + "\n",
            содержимое,
            flags=re.DOTALL,
        )
    elif re.search(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["финансовый_обзор"], содержимое):
        совпадение_годовых = re.search(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["годовые_показатели"], содержимое)
        if совпадение_годовых:
            содержимое = содержимое[: совпадение_годовых.start()] + новая_таблица + "\n\n" + содержимое[совпадение_годовых.start() :]

    содержимое = обновить_метаданные(
        содержимое,
        данные.get("рыночная_капитализация"),
        данные.get("стоимость_предприятия"),
        данные.get("единица_измерения", "млн руб."),
    )

    if пробный_запуск:
        print(f"  {тикер}: черновое обновление ({данные['суффикс']})")
        return True

    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(содержимое)
    print(f"  {тикер}: обновлено ({данные['суффикс']})")
    return True


def main():
    настроить_вывод()

    args = list(sys.argv[1:])
    пробный_запуск = "--пробный-запуск" in args
    if пробный_запуск:
        args.remove("--пробный-запуск")

    тикеры, сектор, описание = разобрать_аргументы_области(args)
    print(f"Обновляю оценочные мультипликаторы для области: {описание}...")
    файлы = найти_файлы_тикеров(тикеры, сектор)

    if not файлы:
        print("Подходящие файлы не найдены.")
        return

    print(f"Найдено файлов: {len(файлы)}.\n")
    обновлено = с_ошибкой = пропущено = 0

    for тикер in sorted(файлы.keys()):
        try:
            if обновить_файл(файлы[тикер], тикер, пробный_запуск):
                обновлено += 1
            else:
                пропущено += 1
        except Exception as ошибка:
            print(f"  {тикер}: ошибка ({ошибка})")
            с_ошибкой += 1
        time.sleep(0.3)

    print(f"\nГотово. Обновлено: {обновлено} | Пропущено: {пропущено} | Ошибок: {с_ошибкой}")


if __name__ == "__main__":
    main()
