"""
update_enrichment.py — Обновление содержимого обогащения (описание, цепочка поставок, клиенты)
в отчётах тикеров. Сохраняет финансовые таблицы.

Этот скрипт применяет данные обогащения из JSON-файла
к файлам отчётов тикеров. Заменяет разделы деятельности, цепочки поставок и контрагентов,
сохраняя метаданные и финансовый блок.

Использование:
  python scripts/update_enrichment.py --данные enrichment.json             # Из JSON-файла
  python scripts/update_enrichment.py --данные enrichment.json SBER        # Один тикер из JSON
  python scripts/update_enrichment.py --данные enrichment.json --сектор Энергетика

Формат JSON:
{
  "SBER": {
    "описание": "Русскоязычное описание с [[викилинки]]...",
    "цепочка_поставок": "**Верхний контур:**\\n- ...\\n**Ключевое звено:**\\n- ...\\n**Конечный спрос:**\\n- ...",
    "клиенты_и_поставщики": "### Ключевые клиенты\\n- ...\\n\\n### Ключевые поставщики\\n- ..."
  }
}

При вызове через Claude /обновить-обогащение навык, Claude:
1. Исследует тикеры через веб-поиск
2. Записывает enrichment.json
3. Запускает этот скрипт
"""

import os
import re
import sys
import json

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from utils import (
    найти_файлы_тикеров, разобрать_аргументы_области, КОРЕНЬ_ПРОЕКТА, нормализовать_викилинки,
    ЗАГОЛОВОК_СЕКЦИИ_ОПИСАНИЯ, ЗАГОЛОВОК_СЕКЦИИ_ЦЕПОЧКИ, ЗАГОЛОВОК_СЕКЦИИ_КЛИЕНТОВ,
    РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ,
)


def применить_обогащение(путь, тикер, данные):
    """Применяет данные обогащения к одному файлу. Сохраняет метаданные и финансовые данные."""
    with open(путь, "r", encoding="utf-8") as ф:
        содержимое = ф.read()

    # Добавляем блок метаданных, если отсутствует
    if not re.search(r"\*\*Сектор:\*\*", содержимое) and not re.search(r"\*\*Рыночная капитализация:\*\*", содержимое):
        сектор = данные.get("сектор", "Н/Д")
        отрасль = данные.get("отрасль", "Н/Д")
        метаданные = (
            f"**Сектор:** {сектор}\n"
            f"**Отрасль:** {отрасль}\n"
            f"**Рыночная капитализация:** Н/Д млн руб.\n"
            f"**Стоимость предприятия (EV):** Н/Д млн руб.\n\n"
        )
        содержимое = re.sub(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["описание_деятельности"] + r"\n", ЗАГОЛОВОК_СЕКЦИИ_ОПИСАНИЯ + "\n" + метаданные, содержимое, count=1)

    # Заменяем описание деятельности (сохраняя блок метаданных выше)
    if "описание" in данные:
        def замена_описания(совпадение):
            return f"{совпадение.group(1)}{данные['описание']}\n"
        содержимое = re.sub(
            r"((?:## Описание деятельности)\n(?:.*?(?:Стоимость предприятия \(EV\)):.*?\n\n|))(.*?)(?=\n(?:## Положение в цепочке поставок))",
            замена_описания,
            содержимое,
            flags=re.DOTALL,
        )

    # Заменяем секцию цепочки поставок
    if "цепочка_поставок" in данные:
        цепочка = данные["цепочка_поставок"] + "\n"
        содержимое = re.sub(
            r"((?:## Положение в цепочке поставок)\n)(.*?)(?=\n(?:## Ключевые клиенты и поставщики))",
            rf"\g<1>{цепочка}",
            содержимое,
            flags=re.DOTALL,
        )

    # Заменяем секцию клиентов/поставщиков
    if "клиенты_и_поставщики" in данные:
        клиенты = данные["клиенты_и_поставщики"] + "\n"
        содержимое = re.sub(
            r"((?:## Ключевые клиенты и поставщики)\n)(.*?)(?=\n(?:## Финансовый обзор))",
            rf"\g<1>{клиенты}",
            содержимое,
            flags=re.DOTALL,
        )

    содержимое = re.sub(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["описание_деятельности"], ЗАГОЛОВОК_СЕКЦИИ_ОПИСАНИЯ, содержимое)
    содержимое = re.sub(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["цепочка_поставок"], ЗАГОЛОВОК_СЕКЦИИ_ЦЕПОЧКИ, содержимое)
    содержимое = re.sub(РЕГЕКСЫ_ЗАГОЛОВКОВ_СЕКЦИЙ["клиенты_и_поставщики"], ЗАГОЛОВОК_СЕКЦИИ_КЛИЕНТОВ, содержимое)

    # Нормализуем викилинки: стандартизируем алиасы, схлопываем дубли
    содержимое = нормализовать_викилинки(содержимое)

    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(содержимое)

    try:
        print(f"  {тикер}: обогащено ({os.path.basename(путь)})")
    except UnicodeEncodeError:
        print(f"  {тикер}: обогащено")
    return True


def загрузить_данные_обогащения(путь_json):
    """Загружает данные обогащения из JSON-файла."""
    with open(путь_json, "r", encoding="utf-8") as ф:
        return json.load(ф)


def главный():
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    аргументы = [элемент for элемент in sys.argv[1:]]

    # Извлекаем флаг --данные
    путь_json = None
    if "--данные" in аргументы:
        индекс = аргументы.index("--данные")
        путь_json = аргументы[индекс + 1]
        аргументы = аргументы[:индекс] + аргументы[индекс + 2:]

    if not путь_json:
        print("Использование: python scripts/update_enrichment.py --данные <json-файл> [область]")
        print("  Область: SBER | SBER GAZP | --сектор Энергетика | без аргументов = все")
        return

    # Загружаем данные обогащения
    if not os.path.isabs(путь_json):
        путь_json = os.path.join(КОРЕНЬ_ПРОЕКТА, путь_json)
    данные_обогащения = загрузить_данные_обогащения(путь_json)
    print(f"Загружено записей по тикерам: {len(данные_обогащения)} из {os.path.basename(путь_json)}")

    # Разбираем область действия
    тикеры, сектор, описание = разобрать_аргументы_области(аргументы)
    print(f"Область применения: {описание}\n")

    # Ищем подходящие файлы
    # Если указаны конкретные тикеры, пересекаем с данными обогащения
    доступные_тикеры = list(данные_обогащения.keys())
    if тикеры:
        целевые_тикеры = [т for т in тикеры if т in данные_обогащения]
    else:
        целевые_тикеры = доступные_тикеры

    файлы = найти_файлы_тикеров(целевые_тикеры, сектор)

    if not файлы:
        print("Подходящие файлы не найдены.")
        return

    обогащено = пропущено = 0
    for тикер in sorted(файлы.keys()):
        if тикер in данные_обогащения:
            применить_обогащение(файлы[тикер], тикер, данные_обогащения[тикер])
            обогащено += 1
        else:
            пропущено += 1

    print(f"\nГотово. Обогащено: {обогащено} | Пропущено: {пропущено}")


if __name__ == "__main__":
    главный()
