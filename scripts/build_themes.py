def русское_множественное(число, форма1, форма2, форма5):
    число = abs(число) % 100
    if 11 <= число <= 19:
        return форма5
    последняя = число % 10
    if последняя == 1:
        return форма1
    if 2 <= последняя <= 4:
        return форма2
    return форма5


