def сканировать_викилинки():
    """Просканировать все отчёты и вернуть карту викилинков с контекстом."""
    карта_викилинков = defaultdict(list)

    for папка_сектора in os.listdir(ДИРЕКТОРИЯ_ОТЧЁТОВ):
        путь_сектора = os.path.join(ДИРЕКТОРИЯ_ОТЧЁТОВ, папка_сектора)
        if not os.path.isdir(путь_сектора):
            continue
        for файл in os.listdir(путь_сектора):
            if not файл.endswith(".md"):
                continue
            совпадение = re.match(rf"^({ШАБЛОН_ТИКЕРА})_(.+)\.md$", файл, re.IGNORECASE)
            if not совпадение:
                continue
            тикер, компания = совпадение.group(1), совпадение.group(2)
            путь_к_файлу = os.path.join(путь_сектора, файл)
            with open(путь_к_файлу, "r", encoding="utf-8") as дескриптор:
                содержимое = дескриптор.read()

            секции = {
                "описание": "",
                "цепочка_поставок": "",
                "клиенты": "",
            }
            части = re.split(r"## ", содержимое)
            for часть in части:
                if re.match(r"^Описание деятельности", часть):
                    секции["описание"] = часть
                elif re.match(r"^Положение в цепочке поставок", часть):
                    секции["цепочка_поставок"] = часть
                elif re.match(r"^Ключевые клиенты и поставщики", часть):
                    секции["клиенты"] = часть

            текст = секции["описание"] + секции["цепочка_поставок"] + секции["клиенты"]
            for викилинк in set(извлечь_викилинки(текст)):
                роль = "связанные"
                if викилинк in секции["цепочка_поставок"]:
                    контекст = секции["цепочка_поставок"].split(викилинк)[0][-100:].lower()
                    if "верх" in контекст:
                        роль = "верхний_контур"
                    elif "ниж" in контекст:
                        роль = "конечный_спрос"
                    elif "средн" in контекст or "ключев" in контекст:
                        роль = "ключевое_звено"

                карта_викилинков[викилинк].append(
                    {
                        "тикер": тикер,
                        "компания": компания,
                        "сектор": папка_сектора,
                        "роль": роль,
                    }
                )

            темы_сектора = СООТВЕТСТВИЕ_СЕКТОРОВ_ТЕМАМ.get(папка_сектора, [])
            for тег_темы in темы_сектора:
                уже_есть = any(
                    эл["тикер"] == тикер for эл in карта_викилинков[тег_темы]
                )
                if not уже_есть:
                    карта_викилинков[тег_темы].append(
                        {
                            "тикер": тикер,
                            "компания": компания,
                            "сектор": папка_сектора,
                            "роль": "ключевое_звено",
                        }
                    )

    return карта_викилинков


def построить_страницу_темы(тег_темы, определение_темы, карта_викилинков):
    """Строит страницу темы в формате markdown."""
    записи = карта_викилинков.get(тег_темы, [])
    if not записи:
        return None

    строки = []
    строки.append(f"# {определение_темы['название']}")
    строки.append("")
    строки.append(f"> {определение_темы['описание']}")
    строки.append("")
    строки.append("**Контур:** активная российская тема | [Ко всем темам](README.md)")
    строки.append("")
    число_записей = len(записи)
    строки.append(f"**Количество компаний:** {число_записей} {русское_множественное(число_записей, 'компания', 'компании', 'компаний')}")
    строки.append("")

    связанные_темы = определение_темы.get("связанные", [])
    связанные_с_количеством = []
    for связанная_тема in связанные_темы:
        количество = len(карта_викилинков.get(связанная_тема, []))
        if количество > 0:
            связанные_с_количеством.append(f"[[{связанная_тема}]] ({количество})")
    if связанные_с_количеством:
        строки.append(f"**Связанные темы:** {' | '.join(связанные_с_количеством)}")
        строки.append("")

    строки.append("---")
    строки.append("")

    верхний_контур = [эл for эл in записи if эл["роль"] == "верхний_контур"]
    ключевое_звено = [эл for эл in записи if эл["роль"] == "ключевое_звено"]
    конечный_спрос = [эл for эл in записи if эл["роль"] == "конечный_спрос"]
    связанные = [эл for эл in записи if эл["роль"] == "связанные"]

    def форматировать_записи(записи):
        по_сектору = defaultdict(list)
        for эл in записи:
            по_сектору[эл["сектор"]].append(эл)
        результат = []
        for сектор in sorted(по_сектору.keys()):
            элементы = sorted(по_сектору[сектор], key=lambda x: x["тикер"])
            for элемент in элементы:
                результат.append(
                    f"- **{элемент['тикер']} {элемент['компания']}** ({сектор})"
                )
        return результат

    if верхний_контур:
        строки.append(f"## Верхний контур ({len(верхний_контур)} {русское_множественное(len(верхний_контур), 'компания', 'компании', 'компаний')})")
        строки.append("")
        строки.extend(форматировать_записи(верхний_контур))
        строки.append("")

    if ключевое_звено:
        строки.append(f"## Ключевое звено ({len(ключевое_звено)} {русское_множественное(len(ключевое_звено), 'компания', 'компании', 'компаний')})")
        строки.append("")
        строки.extend(форматировать_записи(ключевое_звено))
        строки.append("")

    if конечный_спрос:
        строки.append(f"## Конечный спрос ({len(конечный_спрос)} {русское_множественное(len(конечный_спрос), 'компания', 'компании', 'компаний')})")
        строки.append("")
        строки.extend(форматировать_записи(конечный_спрос))
        строки.append("")

    if связанные:
        строки.append(f"## Связанные компании ({len(связанные)} {русское_множественное(len(связанные), 'компания', 'компании', 'компаний')})")
        строки.append("")
        строки.extend(форматировать_записи(связанные))
        строки.append("")

    return "\n".join(строки)


def построить_индекс(построенные_темы):
    """Строит индекс themes/README.md."""
    строки = []
    построено_ру = sum(1 for tag in ТЕМЫ_RU if tag in построенные_темы)
    всего_компаний_ру = sum(построенные_темы[tag] for tag in ТЕМЫ_RU if tag in построенные_темы)

    строки.append("# Тематические подборки")
    строки.append("")
    строки.append("> Автогенерируемые карты цепочек стоимости и смежных компаний.")
    строки.append("> Навигация собрана с российским приоритетом: только российские темы.")
    строки.append("> Пересборка: `python scripts/build_themes.py`")
    строки.append("")
    строки.append(f"> Тем в индексе: {построено_ру}.")
    строки.append("")
    строки.append("---")
    строки.append("")
    строки.append("## Акцент текущего покрытия")
    строки.append("")
    строки.append(
        f"- Российский контур сейчас охватывает {построено_ру} {русское_множественное(построено_ру, 'тему', 'темы', 'тем')} "
        f"и {всего_компаний_ру} тематических вхождений компаний."
    )
    строки.append(f"- Следующая автоматическая очередь `MOEXBMI`: {', '.join(f'`{тикер}`' for тикер in ОЧЕРЕДЬ_ПРИОРИТЕТА_RU)}.")
    строки.append("")

    строки.append("## Российский рынок")
    строки.append("")
    for тег in ТЕМЫ_RU:
        if тег in построенные_темы:
            количество = построенные_темы[тег]
            безопасное_имя = тег.replace(" ", "_").replace("/", "_")
            строки.append(f"- [{тег}]({безопасное_имя}.md) — {количество} {русское_множественное(количество, 'компания', 'компании', 'компаний')}")
    строки.append("")

    return "\n".join(строки)


def main():
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    os.makedirs(ДИРЕКТОРИЯ_ТЕМ, exist_ok=True)

    аргументы = sys.argv[1:]

    if "--список" in аргументы:
        for тег, определение in sorted(ОПРЕДЕЛЕНИЯ_ТЕМ.items()):
            print(f"  {тег}: {определение['название']}")
        return

    print("Сканирую викилинки по всем отчётам...")
    карта_викилинков = сканировать_викилинки()
    print(f"Найдено уникальных викилинков: {len(карта_викилинков)}.\n")

    if аргументы and аргументы[0] != "--список":
        темы_для_построения = {аргументы[0]: ОПРЕДЕЛЕНИЯ_ТЕМ.get(аргументы[0])}
        if not темы_для_построения[аргументы[0]]:
            print(f"Тема '{аргументы[0]}' отсутствует в ОПРЕДЕЛЕНИЯ_ТЕМ. Используйте --список для списка доступных тем.")
            return
    else:
        темы_для_построения = ОПРЕДЕЛЕНИЯ_ТЕМ

    построенные_темы = {}
    for тег, определение in темы_для_построения.items():
        страница = построить_страницу_темы(тег, определение, карта_викилинков)
        if страница:
            безопасное_имя = тег.replace(" ", "_").replace("/", "_")
            путь_к_файлу = os.path.join(ДИРЕКТОРИЯ_ТЕМ, f"{безопасное_имя}.md")
            with open(путь_к_файлу, "w", encoding="utf-8") as ф:
                ф.write(страница)
            количество = len(карта_викилинков.get(тег, []))
            построенные_темы[тег] = количество
            print(f"  {тег}: {количество} {русское_множественное(количество, 'компания', 'компании', 'компаний')} -> {безопасное_имя}.md")

    индекс = построить_индекс(построенные_темы)
    with open(os.path.join(ДИРЕКТОРИЯ_ТЕМ, "README.md"), "w", encoding="utf-8") as ф:
        ф.write(индекс)

    print(f"\nГотово. Сгенерировано тематических страниц: {len(построенные_темы)} в каталоге themes/")


if __name__ == "__main__":
    main()
